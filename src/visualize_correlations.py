def plot_kasiski_summary(txt_file: str, cache: dict) -> None:
    """Extract GCDs from a Kasiski results file and plot the distribution."""
    if not needs_processing(txt_file, cache):
        return
    if not os.path.exists(txt_file):
        return

    gcds: list = []
    with open(txt_file, "r", encoding="utf-8") as f:
        for line in f:
            m = re.search(r"GCD of deltas:\s*(\d+)", line)
            if m:
                gcd_val = int(m.group(1))
                if gcd_val > 1:
                    gcds.append(gcd_val)

